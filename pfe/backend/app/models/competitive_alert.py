"""
Competitive alerts generated by the alert engine.
"""

from sqlalchemy import Column, String, Text, Integer, Float, ForeignKey, DateTime, JSON, Index

from app.models.base import BaseModel


class CompetitiveAlert(BaseModel):
    __tablename__ = "competitive_alerts"

    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, index=True)
    competitor_id = Column(Integer, ForeignKey("competitors.id"), nullable=True, index=True)
    internal_product_id = Column(Integer, ForeignKey("internal_products.id"), nullable=True, index=True)
    competitor_product_id = Column(Integer, ForeignKey("competitor_products.id"), nullable=True, index=True)
    alert_rule_id = Column(Integer, ForeignKey("alert_rules.id"), nullable=True, index=True)

    alert_type = Column(String(80), nullable=False, index=True)
    title = Column(String(255), nullable=False)
    message = Column(Text, nullable=False)
    severity = Column(String(20), nullable=False, default="medium", index=True)
    status = Column(String(30), nullable=False, default="open", index=True)
    signal_score = Column(Float, nullable=True)
    payload = Column(JSON, nullable=True)
    detected_at = Column(DateTime, nullable=True)
    acknowledged_at = Column(DateTime, nullable=True)

    __table_args__ = (
        Index("idx_comp_alerts_user_status", "user_id", "status"),
        Index("idx_comp_alerts_user_type", "user_id", "alert_type"),
    )

